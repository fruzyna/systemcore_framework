package org.wildstang.framework.opmode;

public abstract class WsTeleOpMode extends WsOpMode {

  @Override
  public void disabledPeriodic() {
    super.disabledPeriodic();
  }

  @Override
  public void start() {
    super.start();
  }

  @Override
  public void periodic() {
    super.periodic();
  }

  @Override
  public void end() {
    super.end();
  }

  @Override
  public void close() {
    super.close();
  }
}
